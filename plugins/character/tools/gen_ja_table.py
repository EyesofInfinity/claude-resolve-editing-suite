"""Bakes the Jiles-Atherton stage's unity gain into a C++ table, from our own Python reference.

The Python tape stage (effects/audio/character/tape.py, _magnetise) sets its output gain by running a 1 kHz tone
at -18 dBFS through the loop and matching RMS. The plugin cannot afford that run on the audio thread, so this
script runs the same reference over a grid of drive, hysteresis and asymmetry and writes the gains to
plugins/character/dsp/ja_gain_table.h, which the plugin interpolates.

usage: python -I gen_ja_table.py [sr]
"""
import os
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, os.path.join(REPO, "effects", "audio", "character"))
import common as C
import tape as T

DRIVES = np.arange(-12.0, 30.0 + 0.5, 1.0)
HYST = np.round(np.arange(0.0, 1.0 + 1e-9, 0.1), 6)
ASYM = np.round(np.arange(0.0, 1.0 + 1e-9, 0.1), 6)

def gain(sr, drive_db, hysteresis, asym, oversample=4):
    """The gain g of T._magnetise, computed exactly as it computes it."""
    c = 1.0 - 0.75 * float(np.clip(hysteresis, 0.0, 1.0))
    hpk = T.A_ * C.undb(drive_db)
    bias = float(asym) * 0.6 * T.A_
    f = int(oversample)

    def run(sig):
        up = C.oversample(sig, f) * hpk + bias
        R = int(0.05 * sr) * max(f, 1)
        lead = C.raised(np.arange(R) / R)[:, None] * up[:1]
        m = T._ja(np.ascontiguousarray(np.concatenate([lead, up])), c, T.MS, T.A_, T.K_, T.ALPHA)
        m = m[R:] - m[R - 1]
        return C.undersample(m, f, sig.shape[0])

    t = np.arange(int(0.06 * sr)) / sr
    ref = (C.undb(-18.0) * np.sin(2 * np.pi * 1000.0 * t))[:, None]
    mr = run(ref)
    tail = slice(int(0.03 * sr), None)
    mr = mr - mr[tail].mean()
    return float(np.sqrt(np.mean(ref[tail] ** 2) / max(np.mean(mr[tail] ** 2), 1e-30)))

def main():
    sr = int(sys.argv[1]) if len(sys.argv) > 1 else 48000
    t0 = time.time()
    tab = np.zeros((len(DRIVES), len(HYST), len(ASYM)))
    for i, d in enumerate(DRIVES):
        for j, h in enumerate(HYST):
            for k, a in enumerate(ASYM):
                tab[i, j, k] = gain(sr, d, h, a)
    out = os.path.join(HERE, "..", "dsp", "ja_gain_table.h")
    lines = ["// Generated by plugins/character/tools/gen_ja_table.py from the Python tape reference at %d Hz." % sr,
             "// The unity gain of the Jiles-Atherton stage over drive (dB), hysteresis and asymmetry.",
             "#pragma once",
             "namespace dev {",
             "constexpr double kJaDrive0 = %.1f, kJaDriveStep = 1.0;" % DRIVES[0],
             "constexpr int kJaNd = %d, kJaNh = %d, kJaNa = %d;" % (len(DRIVES), len(HYST), len(ASYM)),
             "static const double kJaGain[%d] = {" % tab.size]
    flat = tab.reshape(-1)
    for i in range(0, flat.size, 6):
        lines.append("    " + ", ".join("%.10e" % v for v in flat[i:i + 6]) + ",")
    lines += ["};", "}  // namespace dev", ""]
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("wrote", os.path.abspath(out), tab.shape, "in %.1f s" % (time.time() - t0))
    print("range", tab.min(), tab.max())

if __name__ == "__main__":
    main()
